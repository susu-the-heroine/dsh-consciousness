/**
 * 「问句要什么值」规则的回归测试（跟任何人的库无关）
 * ==================================================
 *
 * 为什么单独一份：这条规则是在某一个人的库上调出来的，容易只对他的问法有效。
 * 这里用一批跟本机词汇完全不沾的合成语料——咖啡、装修、药、宠物、车——
 * 每次改规则都跑一遍，**误伤必须为 0**。
 *
 * 跑法：node scripts/test-shape-general.mjs
 */
import { answerShape, shapeMissing } from '../lib/gate.js'

// 能答上的：问句要的值，记忆里真有（含中文数字、引号、年份）
const answerable = [
  ['那把铜钥匙的编号是多少', '那把铜钥匙的编号是 KT-7788，挂在门后的钩子上。'],
  ['我那只猫叫什么名字', '她给那只橘猫起名叫“糯米”，因为它小时候走路黏人。'],
  ['上次修冰箱花了多少钱', '修冰箱花了三百二十块，师傅换了启动器。'],
  ['店里的拿铁卖多少', '拿铁小杯十八块，大杯二十一块。'],
  ['哪天交的房租', '房租是三月十二号交的，转账记录还在。'],
  ['装修刷的什么牌子乳胶漆', '刷的是立邦的乳胶漆，色号是珍珠白。'],
  ['他一顿能吃几碗饭', '他一顿能吃三碗饭，还得加个鸡腿。'],
  ['这台车百公里几个油', '这台车百公里七个油，跑高速能到六个。'],
  ['药一天吃几次', '这个药一天吃两次，饭后半小时。'],
  ['她手机号多少', '她手机号是 13800001234，尾号四个数字好记。'],
  ['上次感冒是什么时候', '上次感冒是去年十一月，烧了两天。'],
  ['那个项目叫什么名字', '那个项目起了个名字叫“夜航”，源码在私有仓库。'],
]

// 答不上的：问的是某件具体的事，记忆里只有同类的事，没有那个值
const unanswerable = [
  ['他车牌号多少', '他上个月刚把车洗了一遍，还说轮胎该换了。'],
  ['他家无线网密码多少', '他家里装了光纤，路由器放在客厅电视柜上。'],
  ['我那只狗叫什么名字', '邻居家的狗每天早上叫，吵得人睡不着。'],
  ['这台车百公里几个油', '这台车是去年买的，颜色是深灰。'],
  ['她生日是哪一天', '她去年过生日的时候大家一起吃了火锅。'],
  ['药一天吃几次', '这个药是医生开的，说明书在袋子里。'],
  ['上次修冰箱花了多少钱', '冰箱上周又结霜了，门封不严。'],
  ['他身高多少', '他站在门口，影子拉得很长。'],
  ['哪天交的房租', '房东说下个月开始涨价。'],
  ['店里的拿铁卖多少', '店里新来一个学徒，拉花还不太稳。'],
  ['那个项目叫什么名字', '那个项目拖了三个月，还没上线。'],
  ['装修刷的什么牌子乳胶漆', '装修剩下的漆桶堆在阳台上。'],
]

let hurt = 0
let caught = 0
const bad = []
for (const [q, t] of answerable) {
  if (shapeMissing(q, t)) { hurt++; bad.push('误伤：' + q + '（认成 ' + JSON.stringify(answerShape(q, t)) + '）') }
}
for (const [q, t] of unanswerable) {
  if (shapeMissing(q, t)) caught++
}

console.log('能答上的', answerable.length, '条 → 误伤', hurt, '条（必须为 0）')
console.log('答不上的', unanswerable.length, '条 → 挡住', caught, '条')

if (hurt > 0) {
  console.log('\n逐条看：')
  for (const b of bad) console.log('  ' + b)
  process.exit(1)
}
