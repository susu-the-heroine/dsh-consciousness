// 2026-11-21：以前按「当前工作目录」找库——在别的目录里跑就成了 file:///C:/lib/tools.js，
// 一上来就断。改成按本文件位置算。
const LIB = 'file:///' + join(HERE, '..', 'lib').replace(/\\/g, '/')
const { searchTool } = await import(LIB + '/tools.js')

let top1 = 0
let top3 = 0
const miss = []
for (const [q, want] of asks) {
  const r = await searchTool.execute({ query: q, limit: 5, review: false })
  const ids = [...String(r.log || '').matchAll(/· #(\d+)/g)].map((m) => Number(m[1]))
  const at = ids.indexOf(want)
  if (at === 0) top1++
  if (at >= 0 && at < 3) top3++
  if (at < 0) miss.push(q)
}
const pct = (n) => Math.round((n / asks.length) * 10000) / 100
console.log(`泛化库：${asks.length} 题 · 头名 ${pct(top1)}% · 前三 ${pct(top3)}%`)
if (miss.length) console.log('前三都没进：' + miss.slice(0, 6).join(' / '))
const rate = top1 / asks.length
console.log(rate >= 0.8 ? '泛化地板：过（八成）' : '泛化地板：没过（' + pct(top1) + '% < 80%）')
process.exit(rate >= 0.8 ? 0 : 1)
