/**
 * 意图分类：一句话是在「要东西」还是在「说事」
 * ==========================================
 *
 * 只分三类：op（要东西）/ narr（说事）/ unknown（说不清）。
 * 不做封杀，只用来给"记录型记忆"压分——判错了最多名次掉一点。
 *
 * 为什么不用模型：模型要权重、要训练、要进包；规则够用就先规则。
 * 验收在 scripts/eval-intent.mjs（60 条标注集，准确率 >=85% 才准接）。
 */

const OP = [
  /推荐/, /帮我/, /给我/, /教我/, /帮我想/, /帮我写/, /帮我算/, /帮我起/, /帮我把/,
  /怎么(装|选|写|做|调|下|导|剪|拍|改|买)/, /买/, /在哪(下|买|找)/, /哪个(好|牌子|软件|插件|网站|字体|云)/,
  /多少钱/, /便宜/, /免费/, /能不能出/, /列个/, /起个/, /找.{0,6}(网站|素材|音乐|模板)/,
  /怎么(投|重启|加|配|用|保存|上传)/, /选哪个/, /划算/, /哪个更/,
  /有没有.{0,8}(点|推荐|好用的)/, /怎么让/, /怎么才/,
  // 2026-11-20：标注集里漏过的就是这一种——「你就不能改一下……吗」。
  // 口气是问句，事是要东西。只收这几种明确请求式，别把普通的「吗」也吞进来。
  /你就不能/, /能不能(把|改|加|帮|给)/, /可不可以(把|改|加|帮|给)/, /麻烦.{0,8}(改|加|写|做|换)/,
]

const NARR = [
  /当时/, /那次/, /那天/, /那晚/, /上回/, /上次/, /后来/, /以前/, /从前/, /最后/,
  /记得/, /你说过/, /我说过/, /他(说|问)过/,
  /成了/, /跑通/, /定了/, /上线/, /修好/, /搬进/, /栽了/, /报错/, /泄了/, /崩了/,
  /怎么回事/, /什么感觉/, /哪一天|哪一年|哪一回|哪一条/, /几天|几个月|多久/, /什么时候/,
  /第一次/, /是什么/, /好不好/, /后来怎么样/,
]

function count(list, q) {
  let n = 0
  for (const re of list) if (re.test(q)) n++
  return n
}

/**
 * @param {string} q 用户这句话
 * @returns {'op'|'narr'|'unknown'}
 */
export function classifyIntent(q) {
  const s = String(q || '')
  if (!s.trim()) return 'unknown'
  const t2 = s.trim()
  const op = count(OP, s)
  const narr = count(NARR, s)
  // "能不能改成十秒""帮我看看"——带问号也是要东西，不因为问句就归成说不清。
  // 所以先看有没有明确的"要"，再看是不是在问。
  if (op > 0 && narr === 0) return 'op'
  // 问句不是报告：「你定了吗」「现在有什么提升了」是在问，不是在说事。
  if (/(吗|呢|么|嘛)$/.test(t2) || /[?？]/.test(t2)) return 'unknown'
  if (/(咋|怎么|为啥|为什么|如何|多少|哪个|什么)/.test(t2)) return 'unknown'

  // 两边都像 → 说不清（比如「那个显卡的事后来怎么样了」）
  if (op > 0 && narr > 0) {
    if (op >= narr + 2) return 'op'
    if (narr >= op + 2) return 'narr'
    return 'unknown'
  }
  if (op > 0) return 'op'
  if (narr > 0) return 'narr'


  // 完成体结尾：「……跑通了」「……定了」
  if (/(了|过)$/.test(t2)) return 'narr'
  return 'unknown'
}

export default classifyIntent
