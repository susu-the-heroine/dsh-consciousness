/**
 * 短句尺子的特征（唯一一份）
 * =========================
 * 之前训练脚本里写一套、线上 lib/shortvoice.js 里又一套，两边迟早对不上。
 * 这里只留一份，训练和线上都从这拿。
 *
 * 特征选的不是"长度"，是短句最容易失真的三样：
 *   · 有没有具体物（薯片、锅、电脑）
 *   · 有没有态度（否定、骂、命令）
 *   · 收尾像不像人张嘴（语气词、末尾不点标点）
 * 实测（524 条他的短句 vs 26016 条外来短句）：AUC 0.665。
 * 别把这条当成判决，0.7 才算能用。
 */
export const FEATURE_KEYS = [
  '命令式', '否定', '第一人称', '第二人称', '数字', '英数混', '书面腔',
  '语气尾巴', '末尾无标点', '口头禅', '笑声', '叠字', '省主语', '书面连结', '具体物', '提问', '客套',
]

export function feats(text) {
  const s = String(text || '')
  return {
    // 「你」开头不一定是命令：AI 也说「你可以…」「你应该…」。
    命令式: /^(别|去|先|直接|给我|必须|不要)|^你(?!可以|能|会|应|需|要|想)/.test(s) ? 1 : 0,
    否定: /不|没|别|甭/.test(s) ? 1 : 0,
    第一人称: /我/.test(s) ? 1 : 0,
    第二人称: /你|您/.test(s) ? 1 : 0,
    数字: /\d/.test(s) ? 1 : 0,
    英数混: /[A-Za-z]/.test(s) ? 1 : 0,
    书面腔: /岁月|时光|人生|灵魂|宿命|永恒|汹涌|缱绻|氤氲|斑驳|仿佛|宛若|值得被|皆|乃/.test(s) ? 1 : 0,
    语气尾巴: /[啊吧呢嘛呗呀哈哦咯嘞]\s*[。！？!?]?$/.test(s) ? 1 : 0,
    末尾无标点: /[^。！？!?…~～]$/.test(s) ? 1 : 0,
    口头禅: /卧槽|我草|草|靠|他妈|他吗|妈的|傻|牛|绝了|离谱|真是|行吧|得嘞/.test(s) ? 1 : 0,
    笑声: /哈|嘿|嘻|呵/.test(s) ? 1 : 0,
    叠字: /(.)\1/.test(s) ? 1 : 0,
    省主语: !/^(我|你|他|她|它|咱|这|那|谁)/.test(s) ? 1 : 0,
    书面连结: /因此|所以|并且|然而|此外|综上|首先|其次|最后|总之|换言之/.test(s) ? 1 : 0,
    具体物: /薯片|烟|酒|锅|电脑|手机|视频|剪|素材|游戏|车|路|楼|学校|老师|饭|面|奶茶|狗|猫|钱|数|帧|镜头/.test(s) ? 1 : 0,
    提问: /[?？]|吗|么|咋|啥|哪/.test(s) ? 1 : 0,
    // AI 最爱、她几乎不说的那种语气：你+可以、建议你、希望对你有用。
    客套: /你可以|建议你|如果你|希望对你有|随时告诉我|供你参考|不妨|可以考虑/.test(s) ? 1 : 0,
  }
}

/** 按权重打分：0~1 */
export function scoreWith(weights, text) {
  const f = feats(text)
  let s = 0
  for (const k of Object.keys(weights || {})) {
    if (k === '客套') continue
    s += (f[k] || 0) * (Number(weights[k]) || 0)
  }
  return Math.max(0, Math.min(1, s))
}
